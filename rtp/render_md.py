"""plan.md — the human-readable plan with a Mermaid gantt chart."""
from __future__ import annotations

from pathlib import Path

from .models import EXPOSURE_WEIGHTS, Plan, PlanItem
from .scoring import band

BAND_ICON = {"Low": "🟢", "Medium": "🟡", "High": "🟠", "Critical": "🔴"}


def _esc(text: str) -> str:
    """Escape pipes so free text never breaks a Markdown table."""
    return text.replace("|", "\\|").replace("\n", " ")


def _mermaid_label(text: str) -> str:
    """Mermaid gantt task names cannot contain ':' or ';' and should be short."""
    clean = text.replace(":", " -").replace(";", ",").replace("#", "")
    return clean if len(clean) <= 48 else clean[:45].rstrip() + "..."


def _band_cell(score: int) -> str:
    b = band(score)
    return f"{BAND_ICON[b]} {score} {b}"


def _item_line(item: PlanItem) -> str:
    r = item.risk
    controls = _esc("; ".join(r.planned_controls)) or "—"
    qw = "✅" if item.quick_win else ""
    return (
        f"| {item.rank} | `{r.id}` | {_esc(r.title)} | {_esc(r.owner)} | {_band_cell(r.residual_score)} | "
        f"{r.exposure} | {controls} | {item.effort} | {item.cost_band} | {item.weeks} | "
        f"**{item.priority_score:.2f}** | {qw} |"
    )


_TABLE_HEADER = (
    "| # | ID | Risk | Owner | Residual | Exposure | Planned control | Effort | Cost | Weeks | Priority | Quick win |\n"
    "|---|----|------|-------|----------|----------|-----------------|--------|------|-------|----------|-----------|"
)


def render_md(plan: Plan, path: Path) -> None:
    out: list[str] = []
    planned = plan.planned_items
    total_effort = sum(i.effort for i in planned)
    counts = {b: 0 for b in BAND_ICON}
    for i in plan.items:
        counts[band(i.risk.residual_score)] += 1
    last_end = max((w.end for w in plan.waves if w.end), default=plan.start_date)

    out.append(f"# {plan.title} — risk treatment plan\n")
    out.append(
        f"Generated by `rtp` from the risk register. Start date **{plan.start_date.isoformat()}**, "
        f"wave budget **{plan.wave_budget} effort points**, quick win = residual ≥ {plan.quick_win_score} "
        f"and effort ≤ {plan.quick_win_effort}.\n"
    )
    out.append("## Summary\n")
    out.append("| Metric | Value |\n|--------|-------|")
    out.append(f"| Risks in register | {len(plan.items)} |")
    out.append(f"| Planned for treatment | {len(planned)} |")
    out.append(f"| Accepted (not planned) | {len(plan.unplanned_items)} |")
    out.append(f"| Quick wins | {len(plan.quick_wins)} |")
    out.append(
        "| Residual rating | "
        + " · ".join(f"{BAND_ICON[b]} {b} {n}" for b, n in counts.items())
        + " |"
    )
    out.append(f"| Total planned effort | {total_effort} points |")
    out.append(f"| Plan ends | {last_end.isoformat()} |")
    out.append("")

    # Quick wins
    out.append("## Quick wins\n")
    if plan.quick_wins:
        out.append(
            "High residual score, low effort. Start these this week; they are already in Wave 1 "
            "unless the budget pushed them later.\n"
        )
        out.append(_TABLE_HEADER)
        out.extend(_item_line(i) for i in plan.quick_wins)
    else:
        out.append("None detected with the current thresholds.")
    out.append("")

    # Waves
    for wave in plan.waves:
        out.append(f"## Wave {wave.number}\n")
        if not wave.items:
            out.append("_Empty — the budget was not reached._\n")
            continue
        assert wave.start and wave.end
        out.append(
            f"**{wave.start.isoformat()} → {wave.end.isoformat()}** · {len(wave.items)} treatments · "
            f"{wave.effort} effort points · longest control {wave.weeks} weeks\n"
        )
        out.append(_TABLE_HEADER)
        out.extend(_item_line(i) for i in wave.items)
        out.append("")

    # Not planned
    out.append("## Accepted risks (not planned)\n")
    if plan.unplanned_items:
        out.append(
            "Listed for the record. Acceptance needs a named approver and a review date; "
            "re-run the plan when a risk is no longer accepted.\n"
        )
        out.append("| ID | Risk | Owner | Residual | Existing controls |\n|----|------|-------|----------|-------------------|")
        for i in plan.unplanned_items:
            r = i.risk
            out.append(
                f"| `{r.id}` | {_esc(r.title)} | {_esc(r.owner)} | {_band_cell(r.residual_score)} | "
                f"{_esc(r.existing_controls) or '—'} |"
            )
    else:
        out.append("None.")
    out.append("")

    # Owner workload
    out.append("## Owner workload\n")
    out.append(
        "| Owner | Risks | Planned | Effort | In Wave 1 | Quick wins | Highest residual |\n"
        "|-------|-------|---------|--------|-----------|------------|------------------|"
    )
    for o in plan.owners:
        out.append(
            f"| {_esc(o.owner)} | {o.risks} | {o.planned} | {o.effort} | {o.wave1} | {o.quick_wins} | "
            f"{BAND_ICON[o.highest_band]} {o.highest_band} |"
        )
    heavy = [o for o in plan.owners if o.effort > plan.wave_budget]
    if heavy:
        out.append("")
        out.append(
            "> ⚠️ "
            + ", ".join(f"**{_esc(o.owner)}** ({o.effort} points)" for o in heavy)
            + f" carr{'ies' if len(heavy) == 1 else 'y'} more effort than one wave budget "
            f"({plan.wave_budget}). Consider re-assigning or adding delivery capacity."
        )
    out.append("")

    # Gantt
    out.append("## Timeline\n")
    out.append("```mermaid")
    out.append("gantt")
    out.append(f"    title {_mermaid_label(plan.title)} treatment timeline")
    out.append("    dateFormat YYYY-MM-DD")
    out.append("    axisFormat %b %Y")
    for wave in plan.waves:
        if not wave.items:
            continue
        out.append(f"    section Wave {wave.number}")
        for item in wave.items:
            assert item.wave_start
            tag = "crit, " if item.quick_win else ""
            out.append(
                f"    {item.risk.id} {_mermaid_label(item.risk.title)} :{tag}{item.risk.id.lower()}, "
                f"{item.wave_start.isoformat()}, {item.weeks}w"
            )
    out.append("```\n")

    # Warnings
    if plan.warnings:
        out.append("## Warnings\n")
        out.extend(f"- {_esc(w)}" for w in plan.warnings)
        out.append("")

    # Method
    out.append("## Method\n")
    out.append(
        "`priority = residual score × exposure weight ÷ effort`, where residual score = residual likelihood × "
        "residual impact on the 5×5 grid (Low 1–4 · Medium 5–9 · High 10–16 · Critical 17–25), exposure weight = "
        + " · ".join(f"{k} {v:g}" for k, v in EXPOSURE_WEIGHTS.items())
        + ", and effort is 1 (trivial) to 5 (programme) from the treatment catalogue. "
        "Ties break on residual score, then lower effort, then ID. Waves are filled in rank order until the "
        "cumulative effort budget is reached; the last wave takes the rest. Each wave lasts as long as its slowest control."
    )
    out.append("")

    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
